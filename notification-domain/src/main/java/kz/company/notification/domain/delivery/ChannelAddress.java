package kz.company.notification.domain.delivery;

/**
 * Адрес получателя в конкретном канале. Каждая реализация проверяет формат в конструкторе.
 *
 * <p>Интерфейс открыт: новый канал может принести свой тип адреса.
 */
public interface ChannelAddress {

    /** Значение адреса в каноническом виде. */
    String value();

    /** Значение для логов и публичных ответов: персональные данные замаскированы. */
    String masked();
}
